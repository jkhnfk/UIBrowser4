#!/bin/bash
#
#  build.sh
#  ClickScriptMaker
#
#  Builds the Click Script Maker application bundle.
#
#  Click Script Maker is a standalone application that generates AppleScript and JavaScript for Automation scripts that click the UI element under the mouse pointer. It compiles the ElementLocator.swift and ClickScriptGenerator.swift source files of UI Browser 4, so the generated scripts are identical to the scripts generated by UI Browser's Generate Click Script feature.
#
#  Usage: ./build.sh
#
#  The application bundle is written to build/ClickScriptMaker.app. Pass --install to copy the bundle to ~/Applications after building.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
SHARED_SOURCES="$REPO_ROOT/UIBrowser4/UIBrowser4"
BUILD_DIR="$SCRIPT_DIR/build"
APP_NAME="ClickScriptMaker"
APP_BUNDLE="$BUILD_DIR/$APP_NAME.app"

echo "Building $APP_NAME..."
rm -rf "$APP_BUNDLE"
mkdir -p "$APP_BUNDLE/Contents/MacOS" "$APP_BUNDLE/Contents/Resources"

# The Info.plist and the AppleScript role names resource are copied into the bundle. The property list is shared with UI Browser so that the generated scripts use the same System Events class names, such as "button" instead of "UI element".
cp "$SCRIPT_DIR/Resources/Info.plist" "$APP_BUNDLE/Contents/Info.plist"
cp "$SHARED_SOURCES/AppleScriptRoles.plist" "$APP_BUNDLE/Contents/Resources/AppleScriptRoles.plist"

# Build a native binary for the host architecture. The shared source files are compiled from the UI Browser 4 project so that there is a single copy of the click script generation code.
ARCH="$(uname -m)"
xcrun swiftc \
    -swift-version 5 \
    -O \
    -target "${ARCH}-apple-macos11.0" \
    -o "$APP_BUNDLE/Contents/MacOS/$APP_NAME" \
    "$SCRIPT_DIR"/Sources/*.swift \
    "$SHARED_SOURCES/ElementLocator.swift" \
    "$SHARED_SOURCES/ClickScriptGenerator.swift"

# Sign the bundle so that macOS remembers the Accessibility permission that the user grants it. A Developer ID or Apple Development certificate keeps the permission across rebuilds, because the system identifies the application by its bundle identifier and signing certificate; the ad hoc signature used as a fallback identifies it by the code hash, so the permission must be granted again after every rebuild. The "|| true" keeps the script running when no signing identity is available, because the pipeline fails when security(1) does.
SIGNING_IDENTITY="$(security find-identity -v -p codesigning 2>/dev/null | awk -F'"' '/Developer ID Application|Apple Development/{print $2; exit}')" || true
if [ -n "$SIGNING_IDENTITY" ]; then
    echo "Signing with \"$SIGNING_IDENTITY\"..."
    codesign --force --sign "$SIGNING_IDENTITY" --timestamp=none "$APP_BUNDLE"
else
    echo "No code signing identity found; signing ad hoc..."
    codesign --force --sign - "$APP_BUNDLE"
fi

echo "Built $APP_BUNDLE"

if [ "${1:-}" = "--install" ]; then
    mkdir -p "$HOME/Applications"
    rm -rf "$HOME/Applications/$APP_NAME.app"
    cp -R "$APP_BUNDLE" "$HOME/Applications/$APP_NAME.app"
    echo "Installed $HOME/Applications/$APP_NAME.app"
fi
