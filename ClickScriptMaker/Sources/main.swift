import Cocoa

/**
 The main.swift file launches the Click Script Maker application.

 Click Script Maker is a standalone, single-window application that generates an AppleScript or JavaScript for Automation script that clicks the UI element under the mouse pointer. The application compiles UI Browser 4's *ElementLocator.swift* and *ClickScriptGenerator.swift* source files, so the scripts it generates are identical to the scripts generated by UI Browser's Generate Click Script feature, but the user does not have to run UI Browser or choose a target application.

 The user interface is created entirely in code, so the application has no storyboard and does not call `NSApplicationMain(_:_:)`. Instead, this file creates the application object and its delegate, requests the regular (Dock and menu bar) activation policy, and runs the application. The top-level variables are global variables, so the delegate stays alive for the lifetime of the application.
 */

let application = NSApplication.shared
let applicationDelegate = ClickScriptMakerAppDelegate()
application.delegate = applicationDelegate
application.setActivationPolicy(.regular)
application.run()
