import Cocoa

/**
 The scripting language of a click script generated by `ClickScriptGenerator`.
 */
enum ClickScriptLanguage: Int, CaseIterable {

    /// An AppleScript script to be run by Script Editor, `osascript` or `NSAppleScript`.
    case appleScript = 0

    /// A JavaScript for Automation script to be run by Script Editor or `osascript -l JavaScript`.
    case javaScript = 1

    /// The name of the scripting language as it is displayed to the user.
    var displayName: String {
        switch self {
        case .appleScript:
            return NSLocalizedString("AppleScript", comment: "Name of the AppleScript scripting language")
        case .javaScript:
            return NSLocalizedString("JavaScript", comment: "Name of the JavaScript for Automation scripting language")
        }
    }

    /// The name of the language as it is used in the file name of a saved script.
    var fileExtension: String {
        switch self {
        case .appleScript:
            return "applescript"
        case .javaScript:
            return "js"
        }
    }

}

/**
 A singleton that maps raw accessibility roles such as `AXButton` to the AppleScript class names used by System Events, such as `button`.

 The names are loaded from the *AppleScriptRoles.plist* resource, the same resource used by `ElementDataModel` to display AppleScript terminology. Roles that are missing from the property list are handled as they are in `ElementDataModel.fullAppleScriptDescription(ofElement:)`: a role with Apple's "AX" prefix becomes "UI element" because System Events implements it as a generic UI element, and any other role is used as is.
 */
final class AppleScriptRoleNames {

    // MARK: - PROPERTIES

    /// The singleton instance of `AppleScriptRoleNames`.
    static let shared = AppleScriptRoleNames()

    /// The AppleScript class names keyed by accessibility role.
    private let names: [String: String]

    // MARK: - INITIALIZATION

    private init() {
        if let url = Bundle.main.url(forResource: "AppleScriptRoles", withExtension: "plist"),
            let dictionary = NSDictionary(contentsOf: url) as? [String: String] {
            names = dictionary
        } else {
            names = [:]
        }
    }

    // MARK: - LOOKUP

    /**
     Returns the AppleScript class name that System Events uses for the specified accessibility role.

     - parameter role: The raw accessibility role, e.g. "AXButton".

     - returns: The AppleScript class name, e.g. "button", or "UI element" for unrecognized roles with Apple's "AX" prefix, or the role itself for any other unrecognized role.
     */
    func name(forRole role: String) -> String {
        if let name = names[role] {
            return name
        }
        return role.hasPrefix("AX") ? "UI element" : role
    }

}

/**
 The ClickScriptGenerator.swift file implements the generation of AppleScript and JavaScript for Automation scripts that click a UI element.

 The generator builds the script as plain text, so the user can examine, copy, save and run it with Script Editor or the *osascript* command-line tool. The script locates the UI element by iterating the UI elements of each container in the ancestor chain captured by `ElementLocator`, comparing the accessibility attributes that identify the element, and then performing the element's `AXPress` action or clicking it. Because no screen coordinates appear in the script, it continues to work when the application's windows are moved, resized or restored in a different position.

 Every generated script includes a handler that reads an accessibility attribute of a UI element and returns its value as text, or the empty string if the element does not have the attribute. Reading every identity attribute through this handler keeps the generated script from failing on elements that do not implement the attributes of their peers. Attribute names are used instead of System Events' named properties such as `title` and `role` because the `attribute` class exposes every attribute that the accessibility API makes available, including `AXIdentifier` and `AXDescription`, which are not otherwise part of System Events' terminology.
 */
struct ClickScriptGenerator {

    // MARK: - PROPERTIES

    /// Formats the date and time of generation for the header comment of a generated script.
    private let dateFormatter: DateFormatter = {
        let formatter = DateFormatter()
        formatter.dateStyle = .medium
        formatter.timeStyle = .short
        return formatter
    }()

    // MARK: - GENERATION

    /**
     Generates a script in the specified language that clicks the element described by the anchor.

     - parameter anchor: The `ElementAnchor` captured by `ElementLocator`.

     - parameter language: The scripting language of the generated script.

     - returns: The text of the script.
     */
    func script(for anchor: ElementAnchor, language: ClickScriptLanguage) -> String {
        switch language {
        case .appleScript:
            return appleScript(for: anchor)
        case .javaScript:
            return javaScript(for: anchor)
        }
    }

    // MARK: - HEADER

    /// Returns the header comment lines that describe the element and explain how the script finds it. The comment prefix is "--" for AppleScript and "//" for JavaScript.
    private func headerLines(for anchor: ElementAnchor, commentPrefix: String) -> [String] {
        let bundleIdentifier = anchor.bundleIdentifier.map({ " (\($0))" }) ?? ""
        // Describe how the script identifies the application: by bundle identifier where the application has one, and by name otherwise.
        let applicationLines: [String]
        if anchor.bundleIdentifier == nil {
            applicationLines = [
                "\(commentPrefix) The script identifies the application by the name that System Events displays and locates the UI",
                "\(commentPrefix) element by its accessibility attributes instead of its position on the screen, so it continues",
                "\(commentPrefix) to work when the application's windows are moved, resized or restored in a different position."
            ]
        } else {
            applicationLines = [
                "\(commentPrefix) The script identifies the application by its bundle identifier and locates the UI element by",
                "\(commentPrefix) its accessibility attributes instead of its position on the screen, so it continues to work",
                "\(commentPrefix) when the application's windows are moved, resized or restored in a different position."
            ]
        }
        return [
            "\(commentPrefix) UI Browser Click Script for \(anchor.targetDescription)",
            "\(commentPrefix) Target application: \(anchor.applicationName)\(bundleIdentifier)",
            "\(commentPrefix) Element: \(anchor.pathDescription)",
            "\(commentPrefix) Generated by UI Browser 4 on \(dateFormatter.string(from: Date()))",
            "\(commentPrefix)"
        ] + applicationLines + [
            "\(commentPrefix) Elements are matched by role and by the other identifying attributes; where more than one",
            "\(commentPrefix) element matches, the element's ordinal position among the matching siblings is used."
        ]
    }

    // MARK: - STRING ESCAPING

    /// Returns the string as an AppleScript string literal, including the surrounding quotation marks.
    private func appleScriptString(_ string: String) -> String {
        var escapedString = string.replacingOccurrences(of: "\\", with: "\\\\")
        escapedString = escapedString.replacingOccurrences(of: "\"", with: "\\\"")
        return "\"\(escapedString)\""
    }

    /// Returns the string as a JavaScript string literal, including the surrounding quotation marks.
    private func javaScriptString(_ string: String) -> String {
        var escapedString = string.replacingOccurrences(of: "\\", with: "\\\\")
        escapedString = escapedString.replacingOccurrences(of: "\"", with: "\\\"")
        return "\"\(escapedString)\""
    }

    // MARK: - APPLESCRIPT

    /**
     Generates an AppleScript script that clicks the element described by the anchor.

     The script tells the System Events application to iterate the UI elements of each container in the ancestor chain, so the generated statements mirror the accessibility hierarchy of the target application rather than its screen layout.

     - parameter anchor: The `ElementAnchor` captured by `ElementLocator`.

     - returns: The text of the AppleScript script.
     */
    private func appleScript(for anchor: ElementAnchor) -> String {
        var lines = headerLines(for: anchor, commentPrefix: "--")
        lines.append("")
        lines.append("tell application \"System Events\"")
        lines.append(contentsOf: appleScriptProcessLookupLines(for: anchor))
        lines.append("")
        lines.append("\ttell theApplicationProcess")
        lines.append("\t\t-- Uncomment the next statement to bring \(anchor.applicationName) to the front before clicking.")
        lines.append("\t\t-- set frontmost to true")
        lines.append("")
        lines.append("\t\tset theParentElement to it")

        // Generate the statements that locate each element in the ancestor chain, from the outermost ancestor to the element to be clicked.
        for node in anchor.nodes {
            lines.append("")
            lines.append("\t\t-- \(node.identityDescription)")
            lines.append("\t\tset theTargetElement to missing value")
            lines.append("\t\tset theMatchCount to 0")
            lines.append("\t\trepeat with theIndex from 1 to (count of UI elements of theParentElement)")
            lines.append("\t\t\tset aCandidate to UI element theIndex of theParentElement")
            lines.append(contentsOf: appleScriptConditionLines(for: node, indentation: "\t\t\t"))
            lines.append("\t\t\t\tset theMatchCount to theMatchCount + 1")
            lines.append("\t\t\t\tif theMatchCount is \(node.matchIndex + 1) then set theTargetElement to aCandidate")
            lines.append("\t\t\tend if")
            lines.append("\t\tend repeat")
            let containerDescription = node.role == kAXWindowRole ? "application process \(appleScriptString(anchor.applicationName))" : "its containing element"
            let errorMessage = appleScriptString("UI Browser Click Script: \(node.identityDescription) was not found in \(containerDescription).")
            lines.append("\t\tif theTargetElement is missing value then error \(errorMessage)")
            lines.append("\t\tset theParentElement to theTargetElement")
        }

        // Generate the statements that click the element. The accessibility press action is preferred because it does not depend on the element's position on the screen; a simulated click is the fallback for elements that do not implement the press action.
        lines.append("")
        lines.append("\t\t-- Click the element, preferring the accessibility press action to a simulated mouse click.")
        lines.append("\t\ttry")
        lines.append("\t\t\tperform action \"AXPress\" of theTargetElement")
        lines.append("\t\ton error")
        lines.append("\t\t\tclick theTargetElement")
        lines.append("\t\tend try")
        lines.append("\tend tell")
        lines.append("end tell")

        // Generate the handler that reads an accessibility attribute of a UI element as text.
        lines.append("")
        lines.append("-- Returns the value of the given accessibility attribute of the UI element as text,")
        lines.append("-- or the empty string if the UI element does not have the attribute.")
        lines.append("on attributeText(theElement, theAttributeName)")
        lines.append("\ttell application \"System Events\"")
        lines.append("\t\ttry")
        lines.append("\t\t\tset theValue to value of attribute theAttributeName of theElement")
        lines.append("\t\t\tif theValue is missing value then return \"\"")
        lines.append("\t\t\treturn theValue as text")
        lines.append("\t\tend try")
        lines.append("\tend tell")
        lines.append("\treturn \"\"")
        lines.append("end attributeText")

        return lines.joined(separator: "\n") + "\n"
    }

    /**
     Returns the lines of the AppleScript statements that set the `theApplicationProcess` variable to the process of the application that owns the element to be clicked.

     The application is identified by its bundle identifier because the name that System Events displays for an application is not always the name that the Finder and the accessibility API report, and because the bundle identifier does not change when the application is renamed. The statements fall back on the application's name if no running process has the bundle identifier, as when the application was launched from a copy that has a different bundle identifier. An application that has no bundle identifier at all is identified by its name alone.

     - parameter anchor: The `ElementAnchor` captured by `ElementLocator`.

     - returns: The lines of the AppleScript statements, indented to the top level of the `tell application "System Events"` statement.
     */
    private func appleScriptProcessLookupLines(for anchor: ElementAnchor) -> [String] {
        var lines: [String] = []
        let applicationNotFoundMessage = appleScriptString("UI Browser Click Script: The application \(anchor.applicationName) is not running.")
        // The statements differ depending on whether the captured application had a bundle identifier to identify it by.
        if let bundleIdentifier = anchor.bundleIdentifier {
            lines.append("\t-- Identify the target application by its bundle identifier, which does not change when the")
            lines.append("\t-- application's name changes, and fall back on the name that System Events displays.")
            lines.append("\tset theApplicationProcess to missing value")
            lines.append("\ttry")
            lines.append("\t\tset theMatchingProcesses to (every process whose bundle identifier is \(appleScriptString(bundleIdentifier)))")
            lines.append("\t\tif (count of theMatchingProcesses) > 0 then set theApplicationProcess to item 1 of theMatchingProcesses")
            lines.append("\tend try")
            lines.append("\tif theApplicationProcess is missing value then")
            lines.append("\t\tset theMatchingProcesses to (every process whose name is \(appleScriptString(anchor.applicationName)))")
            lines.append("\t\tif (count of theMatchingProcesses) > 0 then set theApplicationProcess to item 1 of theMatchingProcesses")
            lines.append("\tend if")
        } else {
            lines.append("\t-- Identify the target application by the name that System Events displays, because the UI element")
            lines.append("\t-- was captured without an application bundle identifier.")
            lines.append("\tset theMatchingProcesses to (every process whose name is \(appleScriptString(anchor.applicationName)))")
            lines.append("\tset theApplicationProcess to missing value")
            lines.append("\tif (count of theMatchingProcesses) > 0 then set theApplicationProcess to item 1 of theMatchingProcesses")
        }
        lines.append("\tif theApplicationProcess is missing value then error \(applicationNotFoundMessage)")
        return lines
    }

    /// Returns the lines of the AppleScript `if` statement that tests whether a candidate UI element has every identity attribute of the node, including the `then` keyword but not the body of the statement.
    private func appleScriptConditionLines(for node: ElementAnchor.Node, indentation: String) -> [String] {
        // Each condition calls the attributeText handler because System Events does not implement every accessibility attribute as a named property.
        let conditions = node.identityCriteria.map { criterion in
            return "(my attributeText(aCandidate, \(appleScriptString(criterion.attributeName))) is \(appleScriptString(criterion.value)))"
        }
        var lines: [String] = []
        for (index, condition) in conditions.enumerated() {
            let lastCondition = index == conditions.count - 1
            if index == 0 {
                lines.append("\(indentation)if \(condition)\(lastCondition ? " then" : " and \u{00AC}")")
            } else {
                // The AppleScript line continuation character is the "not" sign, typed as Option-L.
                lines.append("\(indentation)\t\(condition)\(lastCondition ? " then" : " and \u{00AC}")")
            }
        }
        return lines
    }

    // MARK: - JAVASCRIPT FOR AUTOMATION

    /**
     Generates a JavaScript for Automation script that clicks the element described by the anchor.

     The script tells the System Events application to iterate the UI elements of each container in the ancestor chain, so the generated statements mirror the accessibility hierarchy of the target application rather than its screen layout.

     - parameter anchor: The `ElementAnchor` captured by `ElementLocator`.

     - returns: The text of the JavaScript for Automation script.
     */
    private func javaScript(for anchor: ElementAnchor) -> String {
        var lines = headerLines(for: anchor, commentPrefix: "//")
        lines.append("")
        let bundleIdentifierArgument = anchor.bundleIdentifier.map({ javaScriptString($0) }) ?? "null"
        lines.append("const systemEvents = Application(\"System Events\");")
        lines.append("")
        lines.append("// Returns the System Events process object of the target application. The application is")
        lines.append("// identified by its bundle identifier, which does not change when the application's name")
        lines.append("// changes, and by the name that System Events displays if no process has that bundle identifier.")
        lines.append("function findApplicationProcess(bundleIdentifier, processName) {")
        lines.append("    const processes = systemEvents.processes();")
        lines.append("    let processMatchingName = null;")
        lines.append("    for (let processIndex = 0; processIndex < processes.length; processIndex++) {")
        lines.append("        const candidateProcess = processes[processIndex];")
        lines.append("        if (bundleIdentifier !== null) {")
        lines.append("            try {")
        lines.append("                if (String(candidateProcess.bundleIdentifier()) === bundleIdentifier) {")
        lines.append("                    return candidateProcess;")
        lines.append("                }")
        lines.append("            } catch (error) {")
        lines.append("                // Processes that were not launched from an application file have no bundle identifier.")
        lines.append("            }")
        lines.append("        }")
        lines.append("        if (processMatchingName === null && String(candidateProcess.name()) === processName) {")
        lines.append("            processMatchingName = candidateProcess;")
        lines.append("        }")
        lines.append("    }")
        lines.append("    if (processMatchingName !== null) {")
        lines.append("        return processMatchingName;")
        lines.append("    }")
        lines.append("    throw new Error(\"UI Browser Click Script: The application \" + processName + \" is not running.\");")
        lines.append("}")
        lines.append("")
        lines.append("const applicationProcess = findApplicationProcess(\(bundleIdentifierArgument), \(javaScriptString(anchor.applicationName)));")
        lines.append("")
        lines.append("// Returns the value of the given accessibility attribute of the UI element as text,")
        lines.append("// or the empty string if the UI element does not have the attribute.")
        lines.append("function attributeText(uiElement, attributeName) {")
        lines.append("    try {")
        lines.append("        const attributeValue = uiElement.attributes.byName(attributeName).value();")
        lines.append("        return (attributeValue === null || attributeValue === undefined) ? \"\" : String(attributeValue);")
        lines.append("    } catch (error) {")
        lines.append("        // Search the attributes of the element one by one if the attribute cannot be addressed by name.")
        lines.append("    }")
        lines.append("    try {")
        lines.append("        const uiAttributes = uiElement.attributes();")
        lines.append("        for (let attributeIndex = 0; attributeIndex < uiAttributes.length; attributeIndex++) {")
        lines.append("            if (String(uiAttributes[attributeIndex].name()) === attributeName) {")
        lines.append("                const attributeValue = uiAttributes[attributeIndex].value();")
        lines.append("                return (attributeValue === null || attributeValue === undefined) ? \"\" : String(attributeValue);")
        lines.append("            }")
        lines.append("        }")
        lines.append("    } catch (error) {")
        lines.append("        // The element does not implement the attributes of the accessibility API.")
        lines.append("    }")
        lines.append("    return \"\";")
        lines.append("}")
        lines.append("")
        lines.append("// Returns the UI element of the container element whose identifying attributes all have the given")
        lines.append("// values, counting from one. Throws an error if no such element is found.")
        lines.append("function findElement(containerElement, attributeNames, attributeValues, ordinalNumber, elementDescription) {")
        lines.append("    const candidates = containerElement.uiElements();")
        lines.append("    let matchCount = 0;")
        lines.append("    for (let candidateIndex = 0; candidateIndex < candidates.length; candidateIndex++) {")
        lines.append("        const candidate = candidates[candidateIndex];")
        lines.append("        let matches = true;")
        lines.append("        for (let criterionIndex = 0; criterionIndex < attributeNames.length; criterionIndex++) {")
        lines.append("            if (attributeText(candidate, attributeNames[criterionIndex]) !== attributeValues[criterionIndex]) {")
        lines.append("                matches = false;")
        lines.append("                break;")
        lines.append("            }")
        lines.append("        }")
        lines.append("        if (matches) {")
        lines.append("            matchCount = matchCount + 1;")
        lines.append("            if (matchCount === ordinalNumber) {")
        lines.append("                return candidate;")
        lines.append("            }")
        lines.append("        }")
        lines.append("    }")
        lines.append("    throw new Error(\"UI Browser Click Script: \" + elementDescription + \" was not found.\");")
        lines.append("}")
        lines.append("")
        lines.append("let parentElement = applicationProcess;")

        // Generate the statements that locate each element in the ancestor chain, from the outermost ancestor to the element to be clicked.
        for node in anchor.nodes {
            let containerDescription = node.role == kAXWindowRole ? "application process \(javaScriptString(anchor.applicationName))" : "its containing element"
            let elementDescription = javaScriptString("UI Browser Click Script: \(node.identityDescription) was not found in \(containerDescription).")
            let attributeNames = node.identityCriteria.map { javaScriptString($0.attributeName) }
            let attributeValues = node.identityCriteria.map { javaScriptString($0.value) }
            lines.append("")
            lines.append("// \(node.identityDescription)")
            lines.append("parentElement = findElement(parentElement, [\(attributeNames.joined(separator: ", "))], [\(attributeValues.joined(separator: ", "))], \(node.matchIndex + 1), \(elementDescription));")
        }

        // The element to be clicked is the last element found in the ancestor chain.
        lines.append("const targetElement = parentElement;")

        // Generate the statements that click the element.
        lines.append("")
        lines.append("// Click the element, preferring the accessibility press action to a simulated mouse click.")
        lines.append("try {")
        lines.append("    targetElement.actions.byName(\"AXPress\").perform();")
        lines.append("} catch (error) {")
        lines.append("    targetElement.click();")
        lines.append("}")

        return lines.joined(separator: "\n") + "\n"
    }

}
